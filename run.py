def determine_archetype(dna):
    risk = dna.get('risk', 5)
    speed = dna.get('speed', 5)
    empathy = dna.get('empathy', 5)
    verbality = dna.get('verbality', 5)
    if risk >= 7 and speed >= 7:
        return 'strategist'
    elif empathy >= 7 and verbality >= 7:
        return 'motivator'
    else:
        return 'analyst'

